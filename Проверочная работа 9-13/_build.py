def _docx_base():
    from docx import Document
    from docx.shared import Pt, Cm

    d = Document()
    st = d.styles['Normal']
    st.font.name = 'Times New Roman'
    st.font.size = Pt(12)
    st.element.rPr.rFonts.set(
        __import__('docx').oxml.ns.qn('w:eastAsia'), 'Times New Roman')
    pf = st.paragraph_format
    pf.space_after = Pt(0)
    pf.space_before = Pt(0)

    for s in d.sections:
        s.page_width = Cm(21.0)          # A4 — иначе Word печатает на Letter
        s.page_height = Cm(29.7)
        s.left_margin = Cm(2.0)
        s.right_margin = Cm(1.5)
        s.top_margin = Cm(1.2)
        s.bottom_margin = Cm(1.2)
    return d


def _p(doc, text='', size=12, bold=False, italic=False, align=None,
       before=0, after=0, indent=None):
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt

    p = doc.add_paragraph()
    if align == 'c':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == 'j':
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent is not None:
        p.paragraph_format.left_indent = indent
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    if text:
        r = p.add_run(text)
        r.font.size = Pt(size)
        r.bold = bold
        r.italic = italic
        r.font.name = 'Times New Roman'
    return p


def _rule(doc, count=1, height_pt=14.4):
    """Пустые строки с нижней линией — место для письменного ответа.

    Word объединяет подряд идущие абзацы с одинаковыми границами в один блок
    и рисует только внешнюю рамку. Поэтому кроме нижней границы абзаца
    задаём ещё границу w:between — тогда линия появляется между каждой парой
    строк, и получается разлинованное поле для ответа.
    """
    from docx.shared import Pt
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    for i in range(count):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = Pt(height_pt)
        pPr = p._p.get_or_add_pPr()
        bdr = OxmlElement('w:pBdr')
        for tag in ('w:bottom', 'w:between'):
            el = OxmlElement(tag)
            el.set(qn('w:val'), 'single')
            el.set(qn('w:sz'), '6')          # 0.75 pt
            el.set(qn('w:space'), '0')
            el.set(qn('w:color'), '808080')
            bdr.append(el)
        pPr.append(bdr)


def _page_break(doc):
    from docx.enum.text import WD_BREAK
    from docx.shared import Pt
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(0)
    p.add_run().add_break(WD_BREAK.PAGE)


def build_sheet_docx(path):
    from docx.shared import Pt, Cm

    d = _docx_base()
    _p(d, TITLE, 14.5, bold=True, align='c', after=1)
    _p(d, SUBTITLE, 11.5, align='c', after=1)
    _p(d, META, 10, italic=True, align='c', after=1)
    _p(d, SOURCE, 9.5, align='c', after=5)

    tbl = d.add_table(rows=1, cols=3)
    tbl.autofit = False
    widths = [Cm(7.2), Cm(3.6), Cm(3.6)]
    info = [('Фамилия, имя:', 20), ('Класс:', 8), ('Дата:', 10)]
    for ci, (lab, spaces) in enumerate(info):
        c = tbl.cell(0, ci)
        c.width = widths[ci]
        c.text = ''
        p = c.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(lab + ' ')
        r.font.size = Pt(11)
        r.font.name = 'Times New Roman'
        r2 = p.add_run('_' * spaces)
        r2.font.size = Pt(11)
        r2.font.name = 'Times New Roman'
    _p(d, '', 4, after=2)

    _p(d, 'Инструкция', 11, bold=True, after=1)
    for i in INSTR:
        _p(d, '• ' + i, 10, after=1)
    _p(d, '', 4, after=2)

    for t in TASKS:
        head = _p(d, 'Задание %d. %s (%d балла)' % (t['n'], t['short'], t['pts']),
                  12, bold=True, before=5, after=2)
        head.paragraph_format.keep_with_next = True
        for i, it in enumerate(t['items'], 1):
            pre = '' if it['q'][:2] in ('а)', 'б)', 'в)', 'г)') else '%d) ' % i
            q = _p(d, pre + it['q'], 11.5, after=1)
            q.paragraph_format.keep_with_next = True
        _rule(d, ANS_LINES[t['n']])

    _p(d, 'Итого: ______________ / 22          Оценка: ____________',
        11.5, before=0, after=0)
    d.save(path)


